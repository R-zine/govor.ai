"""Live feasibility sources.

The moving diagnostic image and tone are real media tracks generated by the Windows process. They
are intentionally not labeled as a production renderer or speech synthesizer.
"""

from __future__ import annotations

import asyncio
import math
from fractions import Fraction

import numpy as np
from aiortc import AudioStreamTrack, VideoStreamTrack
from av import AudioFrame, VideoFrame


class DiagnosticVideoTrack(VideoStreamTrack):
    """Generate a moving 720p/30 diagnostic scene without a display dependency."""

    def __init__(self, *, width: int = 1280, height: int = 720) -> None:
        super().__init__()
        self.width = width
        self.height = height
        self._frame_number = 0

    async def recv(self) -> VideoFrame:
        pts, time_base = await self.next_timestamp()
        x = np.arange(self.width, dtype=np.uint16)[None, :]
        y = np.arange(self.height, dtype=np.uint16)[:, None]
        phase = self._frame_number * 4
        image = np.empty((self.height, self.width, 3), dtype=np.uint8)
        image[:, :, 0] = ((x + phase) % 256).astype(np.uint8)
        image[:, :, 1] = ((y + phase * 2) % 256).astype(np.uint8)
        image[:, :, 2] = (((x // 2 + y // 2) + phase * 3) % 256).astype(np.uint8)

        marker_x = (self._frame_number * 12) % max(1, self.width - 120)
        image[40:160, marker_x : marker_x + 120, :] = np.array([30, 240, 120], dtype=np.uint8)
        self._frame_number += 1

        frame = VideoFrame.from_ndarray(image, format="bgr24")
        frame.pts = pts
        frame.time_base = time_base
        return frame


class ApplicationAudioTrack(AudioStreamTrack):
    """Generate a quiet application-owned tone at the WebRTC native audio rate."""

    sample_rate = 48_000
    samples_per_frame = 960

    def __init__(self, *, frequency_hz: float = 440.0) -> None:
        super().__init__()
        self.frequency_hz = frequency_hz
        self._sample_cursor = 0
        self._started_at: float | None = None

    async def recv(self) -> AudioFrame:
        loop = asyncio.get_running_loop()
        if self._started_at is None:
            self._started_at = loop.time()
        expected = self._started_at + self._sample_cursor / self.sample_rate
        delay = expected - loop.time()
        if delay > 0:
            await asyncio.sleep(delay)

        positions = np.arange(self.samples_per_frame, dtype=np.float64) + self._sample_cursor
        signal = np.sin(2 * math.pi * self.frequency_hz * positions / self.sample_rate)
        samples = (signal * 2_000).astype(np.int16).reshape(1, -1)
        frame = AudioFrame.from_ndarray(samples, format="s16", layout="mono")
        frame.sample_rate = self.sample_rate
        frame.pts = self._sample_cursor
        frame.time_base = Fraction(1, self.sample_rate)
        self._sample_cursor += self.samples_per_frame
        return frame
